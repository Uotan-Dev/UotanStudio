    /// <summary>Gets every hardware code with a transcribed cell table, in source branch order.
    /// <para>获取所有已转录单元表的硬件代码，顺序与源码分支一致。</para></summary>
    /// <value>
    /// The distinct 16-bit hardware codes covered by <see cref="TryGetCells"/>.
    /// <para><see cref="TryGetCells"/> 覆盖的去重 16 位硬件代码。</para>
    /// </value>
    public static IReadOnlyList<ushort> SupportedHardwareCodes { get; } =
        [.. Groups.SelectMany(group => group.HardwareCodes).Distinct()];

    /// <summary>Gets every group of hardware codes and encoded cells.
    /// <para>获取每个分组的硬件代码与编码单元。</para></summary>
    /// <remarks>
    /// <para>The view is built once at type initialisation from the same arrays the lookup walks, so it
    /// adds no per-call allocation.</para>
    /// <para>该视图在类型初始化时依据查找实际遍历的同一批数组一次性构造，不增加每次调用的分配。</para>
    /// </remarks>
    /// <value>
    /// The hardware codes and encoded cells of each group, in table order.
    /// <para>每个分组的硬件代码与编码单元，按表顺序排列。</para>
    /// </value>
    internal static IReadOnlyList<(IReadOnlyList<ushort> HardwareCodes, IReadOnlyList<ulong> Cells)> TranscribedGroups { get; } =
        [.. Groups.Select(group => (
            (IReadOnlyList<ushort>)group.HardwareCodes,
            (IReadOnlyList<ulong>)group.Cells))];

    /// <summary>Gets whether a cell table exists for the hardware code.
    /// <para>获取该硬件代码是否存在单元表。</para></summary>
    /// <param name="hardwareCode">The hardware code to look up. 要查找的硬件代码。</param>
    /// <returns>
    /// <see langword="true"/> when a transcribed table covers <paramref name="hardwareCode"/>.
    /// <para>转录的表覆盖 <paramref name="hardwareCode"/> 时为 <see langword="true"/>。</para>
    /// </returns>
    public static bool IsSupported(ushort hardwareCode) => TryGetCells(hardwareCode, out _);

    /// <summary>Copies the raw encoded cell table for one hardware code.
    /// <para>复制某个硬件代码的原始编码单元表。</para></summary>
    /// <remarks>
    /// A hardware code with no group is reported as a lookup miss rather than guessed from a
    /// neighbouring chip's table.
    /// <para>没有对应分组的硬件代码上报为查找失败，而不用相邻芯片的表近似。</para>
    /// </remarks>
    /// <param name="hardwareCode">The hardware code to look up. 要查找的硬件代码。</param>
    /// <param name="cells">Receives the encoded cells, in table order, when the lookup succeeds.
    /// <para>查找成功时按表顺序接收编码单元。</para></param>
    /// <returns>
    /// <see langword="true"/> when a table exists. <see langword="false"/> leaves
    /// <paramref name="cells"/> empty.
    /// <para>存在表时为 <see langword="true"/>；返回 <see langword="false"/> 时 <paramref name="cells"/> 为空。</para>
    /// </returns>
    public static bool TryGetCells(ushort hardwareCode, out ulong[] cells)
    {
        foreach (var (hardwareCodes, table) in Groups)
        {
            if (hardwareCodes.Contains(hardwareCode))
            {
                cells = [.. table];
                return true;
            }
        }

        cells = [];
        return false;
    }

    /// <summary>Gets the largest cell table the evidence contains.
    /// <para>获取证据中最大单元表的大小。</para></summary>
    /// <value>
    /// The cell count of the longest transcribed table.
    /// <para>转录表中最长一条的单元数量。</para>
    /// </value>
    public static int MaximumCellCount { get; } = Groups.Max(group => group.Cells.Length);

    /// <summary>Reports whether an encoded cell carries the absolute-address marker.
    /// <para>报告编码单元是否带有绝对地址标记。</para></summary>
    /// <param name="cell">One value from <see cref="TryGetCells"/>. <see cref="TryGetCells"/> 返回的一个取值。</param>
    /// <returns>
    /// <see langword="true"/> when the cell is an absolute address rather than a base-relative offset.
    /// <para>单元为绝对地址而非基准相对偏移时为 <see langword="true"/>。</para>
    /// </returns>
    public static bool IsAbsolute(ulong cell) => (cell & AbsoluteMarker) != 0;
