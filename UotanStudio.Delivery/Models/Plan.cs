/// <summary><para>显式单设备 LP 布局；尺寸单位均为字节，不使用稀疏文件长度。</para>
/// Explicit single-device LP layout; sizes are bytes, never sparse file lengths.</summary>
public sealed record DeliverySuperOptions
{
    /// <summary>
    /// Zstd level used when compressing the Super image. Defaulted to 19 so repacking the original
    /// package's partitions does not exceed the original Super image size, which the library default
    /// level 3 frequently fails to match.
    /// <para>压缩 Super 镜像时使用的 Zstd 等级。默认提高到 19：重打包原包分区镜像时，压缩后的
    /// super.zst 不应比原始 super 镜像更大，而库默认的 3 级往往压不过原包。</para>
    /// </summary>
    internal const int DefaultZstdLevel = 19;

    /// <summary>
    /// Zstd compression level; 0 or values outside 1..22 fall back to <see cref="DefaultZstdLevel"/>.
    /// <para>Zstd 压缩等级；0 或超出 1..22 时回退到 <see cref="DefaultZstdLevel"/>。</para>
    /// </summary>
    public int ZstdLevel { get; init; } = DefaultZstdLevel;

    /// <summary>
    /// Resolves the effective Zstd level for this Super compression: a valid value is used as-is,
    /// otherwise the default applies (older plan JSON missing the field deserializes to 0).
    /// <para>解析本次 Super 压缩实际使用的 Zstd 等级：合法值原样使用，否则回退到默认等级
    /// （旧计划 JSON 缺省该字段时反序列化为 0）。</para>
    /// </summary>
    internal static int ResolveZstdLevel(DeliverySuperOptions options) =>
        options.ZstdLevel is >= 1 and <= 22 ? options.ZstdLevel : DefaultZstdLevel;

    /// <summary>
    /// Switch for the Super Zstd container layout, off by default: off emits one streaming frame, on splits the input into 1 MiB chunks encoded concurrently. The two layouts decode to the same plaintext but are not byte-equal. The chunked layout is emitted on every host: a worker cap of <c>1</c> still compresses this step with two workers, so one plan never yields different container bytes depending on the machine that built it.
    /// <para>Super 的 Zstd 容器布局开关，默认关闭：关闭时输出单个流式帧，打开时按 1 MiB 切块并发编码。两种布局解码后的明文相同，但容器字节并不逐字节相等。打开后在任何主机上都会输出切块布局：并行数量上限为 <c>1</c> 时这一步仍然使用两个工作者，因此同一个计划不会因为构建机器不同而产出不同的容器字节。</para>
    /// </summary>
    public bool ZstdChunkedParallel { get; init; }

    /// <summary>
    /// Super block-device size in bytes. There is no usable default: a value above the real partition makes liblp refuse the metadata and every dynamic partition unavailable, while a value below it leaves unallocated tail space and breaks later OTA snapshot allocation.
    /// <para>Super 块设备大小（字节）。没有可用的默认值：大于真实分区会使 liblp 拒绝元数据、所有动态分区不可用；小于真实分区则留下未分配尾部空间，并使后续 OTA 快照分配失败。</para>
    /// </summary>
    public ulong DeviceSize { get; init; }
    /// <summary>
    /// Gets or sets the MetadataSize value.
    /// <para>获取或设置 MetadataSize 值。</para>
    /// </summary>
    public uint MetadataSize { get; init; } = 65536;
    /// <summary>
    /// Gets or sets the Slots value.
    /// <para>获取或设置 Slots 值。</para>
    /// </summary>
    public uint Slots { get; init; } = 3;
    /// <summary>
    /// Gets or sets the BlockSize value.
    /// <para>获取或设置 BlockSize 值。</para>
    /// </summary>
    public uint BlockSize { get; init; } = 4096;
    /// <summary>
    /// Gets or sets the Group value.
    /// <para>获取或设置 Group 值。</para>
    /// </summary>
    public string Group { get; init; } = "qti_dynamic_partitions";
    /// <summary>
    /// Gets or sets the DeviceName value.
    /// <para>获取或设置 DeviceName 值。</para>
    /// </summary>
    public string DeviceName { get; init; } = "super";
    /// <summary>
    /// Gets or sets the Sparse value.
    /// <para>获取或设置 Sparse 值。</para>
    /// </summary>
    public bool Sparse { get; init; }
    /// <summary>
    /// Gets or sets the VirtualAb value.
    /// <para>获取或设置 VirtualAb 值。</para>
    /// </summary>
    public bool VirtualAb { get; init; }
    /// <summary>
    /// Gets or sets the DeviceType value.
    /// <para>获取或设置 DeviceType 值。</para>
    /// </summary>
    public string DeviceType { get; init; } = "";
    /// <summary>
    /// Gets or sets the AutoZero value.
    /// <para>获取或设置 AutoZero 值。</para>
    /// </summary>
    public bool AutoZero { get; init; }
    /// <summary>
    /// Gets or sets the Empty value.
    /// <para>获取或设置 Empty 值。</para>
    /// </summary>
    public bool Empty { get; init; }
    /// <summary>
    /// Gets or sets the Zstd value.
    /// <para>获取或设置 Zstd 值。</para>
    /// </summary>
    public bool Zstd { get; init; }
    /// <summary>
    /// Gets or sets the Groups value.
    /// <para>获取或设置 Groups 值。</para>
    /// </summary>
    public List<DeliveryGroup> Groups { get; init; } = [];
}

