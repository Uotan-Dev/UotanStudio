/// <summary>One immutable file or partition in a delivery snapshot. <para>交付快照中的单个不可变文件或分区条目。</para></summary>
public sealed record DeliveryFile
{
    /// <summary>Full path of the source image; empty for generated entries. <para>源镜像的完整路径；生成的条目为空。</para></summary>
    public string SourcePath { get; init; } = "";
    /// <summary>Output filename base name (directory excluded). <para>输出文件基名（不含目录）。</para></summary>
    public string FileName { get; init; } = "";
    /// <summary>Target partition name. <para>目标分区名。</para></summary>
    public string Partition { get; init; } = "";
    /// <summary>Partition choice group this entry belongs to. <para>条目所属的分区选择组。</para></summary>
    public string SourceGroup { get; init; } = "";
    /// <summary>Whether this is an optional alternative image. <para>是否为可选的替换镜像。</para></summary>
    public bool Optional { get; init; }
    /// <summary>Whether this is the default image of its partition choice group. <para>是否为此分区选择组的默认镜像。</para></summary>
    public bool Default { get; init; }
    /// <summary>Whether this entry is generated by the delivery (e.g., the payload/super container). <para>是否为交付过程生成的条目（如 payload/super 容器）。</para></summary>
    public bool Generated { get; init; }
    /// <summary>Source length captured at staging time, used to detect source changes. <para>暂存时记录的源长度；用于检测源是否变化。</para></summary>
    public long? SourceLength { get; init; }
    /// <summary>Whether this is included in the Super as a dynamic partition member. <para>是否作为动态分区实体包含进 Super。</para></summary>
    public bool IncludeInSuper { get; init; }
    /// <summary>Whether flashing requires fastbootd userspace mode. <para>是否需要在 fastbootd 用户空间模式下刷写。</para></summary>
    public bool Fastbootd { get; init; }
    /// <summary>Auto-added zero-size partition (VAB B-slot companion); read-only and exempt from the empty-image check. <para>自动添加的零大小分区条目（VAB B 槽伴随），不可编辑且豁免空镜像检查。</para></summary>
    public bool AutoZero { get; init; }
    /// <summary>
    /// Equivalence metadata the host attaches when the image came out of a preserved rebuild, keyed as the library's equivalence report documents. Null or empty means there is no evidence, so delivery verifies only the byte dimension. Valid in this process only.
    /// <para>宿主在该镜像出自受保留重建后附上的等价元数据，键名与库的等价报告一致。为 null 或空表示无证据，此时交付只校验字节维度。仅在本次进程内有效。</para>
    /// </summary>
    /// <value>The equivalence metadata dictionary, or null. <para>等价元数据字典，或 null。</para></value>
    public Dictionary<string, string>? RebuildEquivalence { get; init; }
}

