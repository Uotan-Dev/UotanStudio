/// <summary>
/// Builds the OTA-package and delivery-preparation MCP tools backed by <see cref="OtaZipPatchService"/>,
/// <see cref="SuperPayloadConversionService"/> and <see cref="DeliveryService"/>, exposing the Delivery
/// capabilities that had no MCP entry point: OTA ZIP verification, bounded member patching, payload-centric
/// rebuild, Super-to-Payload conversion and pinned platform-tool preparation.
/// <para>基于 <see cref="OtaZipPatchService"/>、<see cref="SuperPayloadConversionService"/> 与
/// <see cref="DeliveryService"/> 构建 OTA 包与交付准备类 MCP 工具，暴露此前没有 MCP 入口的交付能力：
/// OTA ZIP 校验、受限成员修补、以 Payload 为中心的重建、Super 转 Payload，以及钉定版本平台工具的准备。</para>
/// Each delegate ends with the ambient parameters the MCP server binds itself
/// (<see cref="IProgress{T}"/> only where the backing API reports progress, plus
/// <see cref="CancellationToken"/>); neither appears in the emitted <c>inputSchema</c>, so clients cannot
/// pass them but cancellation and progress propagate into the backing calls that accept them.
/// <para>每个委托都以 MCP 服务器自行绑定的环境参数结尾（只有在底层 API 会上报进度时才带
/// <see cref="IProgress{T}"/>，外加 <see cref="CancellationToken"/>）；两者都不出现在生成的
/// <c>inputSchema</c> 中，客户端无法传入，但取消与进度会传导到接受它们的底层调用。</para>
/// </summary>
internal static class OtaToolFactory
{
    internal static IReadOnlyList<McpServerTool> CreateTools(PathSandbox sandbox)
    {
        var verify = McpServerTool.Create(
            ([Description("A/B OTA or recovery ZIP path inside the sandbox.")] string zipPath,
             CancellationToken cancellationToken = default) => ToolGuard.RunAsync(
                token => OtaToolHandlers.VerifyAsync(sandbox, zipPath, token), cancellationToken),
            new McpServerToolCreateOptions
            {
                Name = "ota_zip_verify",
                Description = "Verify an existing OTA ZIP without writing anything: duplicate or oversized "
                    + "members, missing payload_properties.txt, invalid CrAU magic, and FILE_HASH, FILE_SIZE, "
                    + "METADATA_HASH or METADATA_SIZE disagreement with the stored payload. A ZIP without "
                    + "payload.bin is reported as valid with a recovery-package warning.",
                ReadOnly = true,
                Idempotent = true,
                OpenWorld = false,
                Destructive = false
            });

        var patch = McpServerTool.Create(
            ([Description("Source OTA ZIP path inside the sandbox; read only and never modified.")] string inputPath,
             [Description("Destination ZIP path inside the sandbox; replaced atomically once the archive is complete.")] string outputPath,
             [Description("JSON object mapping OTA ZIP member names to local sandbox file paths, e.g. {\"updater-script\":\"scripts/updater-script\"}. Members not listed are copied unchanged and unknown keys are appended.")] string? replacementsJson = null,
             [Description("Authorise replacing payload.bin. Unsupported by update_engine: the CrAU header, payload_properties.txt and META-INF/com/android/metadata offsets are not regenerated by this call, so the flashed package fails verification. Use ota_zip_rebuild instead unless you have rebuilt those three artifacts yourself.")] bool allowPayloadReplacement = false,
             CancellationToken cancellationToken = default) => ToolGuard.RunAsync(
                token => OtaToolHandlers.PatchAsync(sandbox, inputPath, outputPath, replacementsJson,
                    allowPayloadReplacement, token), cancellationToken),
            new McpServerToolCreateOptions
            {
                Name = "ota_zip_patch",
                Description = "Replace selected ZIP members of an existing A/B OTA package and publish the "
                    + "rewritten archive. Members are rewritten unstored in source order, each capped at "
                    + "16 GiB, and the outer OTA signature block under META-INF/com/android/ is always "
                    + "dropped, so the output must be re-signed or accepted unsigned. Cancelling keeps the "
                    + "destination's previous content.",
                ReadOnly = false,
                Idempotent = false,
                OpenWorld = false,
                Destructive = false
            });

        var rebuild = McpServerTool.Create(
            ([Description("Existing OTA ZIP supplying the copied-through members and the metadata base.")] string inputPath,
             [Description("Destination OTA ZIP path inside the sandbox; published only after verification.")] string outputPath,
             [Description("Replacement payload.bin inside the sandbox: CrAU version 2 or 3, at most 16 GiB, manifest plus metadata-signature prefix within 64 MiB.")] string payloadPath,
             [Description("JSON object of extra member-name to local sandbox file path replacements. payload.bin, payload_properties.txt, META-INF/com/android/metadata and META-INF/com/android/otacert are owned by the rebuild and rejected here.")] string? replacementsJson = null,
             [Description("Outer certificate file (PEM or DER, at most 64 KiB) inside the sandbox; empty leaves the package unsigned and its original otacert untouched. Must be set together with signingKeyPath.")] string certificatePath = "",
             [Description("Private key file inside the sandbox whose public key must match the certificate; empty produces an unsigned but structurally valid OTA. Must be set together with certificatePath.")] string signingKeyPath = "",
             [Description("When false the verification result is still computed and returned but a failure no longer blocks publication.")] bool verifyOutput = true,
             CancellationToken cancellationToken = default) => ToolGuard.RunAsync(
                token => OtaToolHandlers.RebuildAsync(sandbox, inputPath, outputPath, payloadPath,
                    replacementsJson, certificatePath, signingKeyPath, verifyOutput, token), cancellationToken),
            new McpServerToolCreateOptions
            {
                Name = "ota_zip_rebuild",
                Description = "Rebuild an existing A/B OTA around a replacement payload.bin: regenerates "
                    + "payload_properties.txt and the META-INF/com/android/metadata streaming offsets, "
                    + "optionally signs the whole file, verifies the staged archive and publishes it "
                    + "atomically. Reports the final verification state of the published archive.",
                ReadOnly = false,
                Idempotent = false,
                OpenWorld = false,
                Destructive = false
            });

        var convert = McpServerTool.Create(
            ([Description("Source LP Super image path inside the sandbox; read only.")] string superPath,
             [Description("Destination payload.bin path inside the sandbox. Its companion payload_properties.txt is always written into the same directory.")] string payloadPath,
             [Description("Payload block size in bytes; a power of two from 512 through 1048576 and every extracted partition must be a multiple of it.")] uint blockSize = 4096,
             [Description("Install-operation codec: None, BZip2 or Xz. Other payload codecs are rejected by the delivery plan validation.")] string compression = "None",
             [Description("Maximum timestamp written into the manifest, seconds since the Unix epoch; 0 omits a bound.")] long maxTimestamp = 0,
             [Description("Android security patch level as yyyy-MM-dd; empty omits the property.")] string securityPatchLevel = "",
             IProgress<ProgressNotificationValue>? progress = null,
             CancellationToken cancellationToken = default) => ToolGuard.RunAsync(
                token => OtaToolHandlers.ConvertSuperAsync(sandbox, superPath, payloadPath, blockSize,
                    compression, maxTimestamp, securityPatchLevel, progress, token), cancellationToken),
            new McpServerToolCreateOptions
            {
                Name = "super_payload_convert",
                Description = "Convert a Super image into a full update_engine payload.bin plus "
                    + "payload_properties.txt: every non-empty logical partition is extracted to a staging "
                    + "directory, the generated manifest is re-parsed to prove it carries each partition, and "
                    + "both files publish only then, restoring prior outputs on failure. Send a progress token "
                    + "to receive notifications/progress. This entry point has no signing-key provider, so the "
                    + "payload is always unsigned.",
                ReadOnly = false,
                Idempotent = false,
                OpenWorld = false,
                Destructive = false
            });

        var prepareTools = McpServerTool.Create(
            ([Description("Delivery plan JSON (DeliveryPlan schema; paths sandbox-relative or absolute inside the sandbox). The windows/linux/macOS flags decide which platform bundles are fetched.")] string planJson,
             [Description("Directory that receives the bin/ tool layout; must stay inside the sandbox. Empty falls back to the plan's outputDirectory.")] string directory = "",
             IProgress<ProgressNotificationValue>? progress = null,
             CancellationToken cancellationToken = default) => ToolGuard.RunAsync(
                token => OtaToolHandlers.PrepareToolsAsync(sandbox, planJson, directory, progress, token),
                cancellationToken),
            new McpServerToolCreateOptions
            {
                Name = "delivery_prepare_tools",
                Description = "Prepare the platform-tools and zstd binaries a delivery plan needs into a "
                    + "bin/ layout. Requires network access to dl.google.com and github.com and writes a "
                    + "checksum-verified cache outside the sandbox under the current user's application-data "
                    + "directory, so it can fail on an offline or restricted host; this path is not covered "
                    + "by automated tests. Repeated calls reuse the cached archives.",
                ReadOnly = false,
                Idempotent = false,
                OpenWorld = true,
                Destructive = false
            });

        return [verify, patch, rebuild, convert, prepareTools];
    }
}

/// <summary>
/// Implementations for the OTA and delivery-preparation tool delegates; kept separate for direct unit testing.
/// <para>OTA 与交付准备工具委托的实现；独立存放便于直接单元测试。</para>
/// Every handler resolves its client paths through the <see cref="PathSandbox"/> before the backing call
/// runs, returns the <see cref="ToolResult"/> envelope, and threads the caller's
/// <see cref="CancellationToken"/> only into the backing APIs whose signature accepts one;
/// <see cref="ToolGuard"/> turns the envelope into the protocol result.
/// <para>每个处理器在调用底层前先用 <see cref="PathSandbox"/> 解析客户端路径，返回
/// <see cref="ToolResult"/> 信封，并且只把调用方的 <see cref="CancellationToken"/> 传给签名接受它的底层 API；
/// 由 <see cref="ToolGuard"/> 把信封转为协议结果。</para>
/// </summary>
internal static class OtaToolHandlers
{
    private const int MaximumListedToolFiles = 512;

    /// <summary>
    /// <para>工具下载共用的 HTTP 客户端；platform-tools 与 zstd 归档可达数百 MiB，因此不设请求超时，
    /// 中止只由请求的取消令牌驱动。</para>
    /// Shared client for the tool downloads; platform-tools and zstd archives reach hundreds of MiB, so no
    /// request timeout applies and stopping is driven only by the request's cancellation token.
    /// </summary>
    private static readonly HttpClient ToolHttpClient = new() { Timeout = Timeout.InfiniteTimeSpan };

    public static async Task<ToolResult> VerifyAsync(
        PathSandbox sandbox, string zipPath, CancellationToken cancellationToken)
        => await Task.Run(() =>
        {
            var resolved = sandbox.Resolve(zipPath, mustExist: true);
            var verification = OtaZipPatchService.Verify(resolved);
            return new ToolResult(verification.IsValid,
                verification.IsValid
                    ? $"OTA ZIP is valid with {verification.Warnings.Count} warning(s)."
                    : $"OTA ZIP failed with {verification.Errors.Count} error(s): {Summarise(verification.Errors)}",
                ToolJson.Data(ToVerificationPayload(resolved, verification)));
        }, cancellationToken).ConfigureAwait(false);

    public static async Task<ToolResult> PatchAsync(
        PathSandbox sandbox, string inputPath, string outputPath, string? replacementsJson,
        bool allowPayloadReplacement, CancellationToken cancellationToken)
    {
        var resolvedInput = sandbox.Resolve(inputPath, mustExist: true);
        var resolvedOutput = sandbox.ResolveOutput(outputPath);
        var result = await OtaZipPatchService.PatchAsync(
            resolvedInput,
            resolvedOutput,
            new OtaZipPatchOptions
            {
                ReplacementFiles = ParseReplacements(sandbox, replacementsJson),
                AllowPayloadReplacement = allowPayloadReplacement
            },
            cancellationToken).ConfigureAwait(false);
        return new ToolResult(true,
            $"Patched {result.ReplacedEntries.Count} OTA ZIP member(s) into {result.OutputPath}; "
            + "the outer OTA signature was invalidated.",
            ToolJson.Data(new OtaZipPatchPayload(
                resolvedInput,
                result.OutputPath,
                result.ReplacedEntries,
                result.OuterSignatureInvalidated,
                new FileInfo(result.OutputPath).Length)));
    }

    public static async Task<ToolResult> RebuildAsync(
        PathSandbox sandbox, string inputPath, string outputPath, string payloadPath,
        string? replacementsJson, string certificatePath, string signingKeyPath, bool verifyOutput,
        CancellationToken cancellationToken)
    {
        var resolvedInput = sandbox.Resolve(inputPath, mustExist: true);
        var resolvedOutput = sandbox.ResolveOutput(outputPath);
        var result = await OtaZipPatchService.RebuildAsync(
            resolvedInput,
            resolvedOutput,
            new OtaZipRebuildOptions
            {
                PayloadPath = sandbox.Resolve(payloadPath, mustExist: true),
                ReplacementFiles = ParseReplacements(sandbox, replacementsJson),
                CertificatePath = ResolveOptionalInput(sandbox, certificatePath),
                SigningKeyPath = ResolveOptionalInput(sandbox, signingKeyPath),
                VerifyOutput = verifyOutput
            },
            cancellationToken).ConfigureAwait(false);
        return new ToolResult(true,
            $"Rebuilt OTA at {result.OutputPath} writing {result.ReplacedEntries.Count} member(s)"
            + (result.OuterSignatureApplied ? " with the outer signature applied." : " without an outer signature.")
            + (result.Verification.IsValid ? "" : " Published verification reported "
                + $"{result.Verification.Errors.Count} error(s)."),
            ToolJson.Data(new OtaZipRebuildPayload(
                resolvedInput,
                result.OutputPath,
                result.ReplacedEntries,
                result.OuterSignatureApplied,
                ToVerificationPayload(result.OutputPath, result.Verification))));
    }

    public static async Task<ToolResult> ConvertSuperAsync(
        PathSandbox sandbox, string superPath, string payloadPath, uint blockSize, string compression,
        long maxTimestamp, string securityPatchLevel, IProgress<ProgressNotificationValue>? progress,
        CancellationToken cancellationToken)
    {
        if (!Enum.TryParse(compression, ignoreCase: true, out CompressionType codec)
            || codec is not (CompressionType.None or CompressionType.BZip2 or CompressionType.Xz))
        {
            return new ToolResult(false,
                $"Payload compression must be None, BZip2 or Xz; '{compression}' is not accepted by the "
                + "delivery payload validation.");
        }

        var resolvedSuper = sandbox.Resolve(superPath, mustExist: true);
        var resolvedPayload = sandbox.ResolveOutput(payloadPath);
        var result = await SuperPayloadConversionService.ConvertAsync(
            resolvedSuper,
            resolvedPayload,
            new SuperPayloadConversionOptions
            {
                BlockSize = blockSize,
                Compression = codec,
                MaxTimestamp = maxTimestamp,
                SecurityPatchLevel = securityPatchLevel
            },
            ToTextProgress(progress),
            cancellationToken).ConfigureAwait(false);
        return new ToolResult(true,
            $"Converted Super into a full Payload carrying {result.Partitions.Count} partition(s)"
            + (result.VirtualAb ? " with virtual-A/B declared." : "."),
            ToolJson.Data(new SuperPayloadConversionPayload(
                resolvedSuper,
                result.PayloadPath,
                result.PropertiesPath,
                result.Partitions,
                result.VirtualAb)));
    }

    public static async Task<ToolResult> PrepareToolsAsync(
        PathSandbox sandbox, string planJson, string directory, IProgress<ProgressNotificationValue>? progress,
        CancellationToken cancellationToken)
    {
        var plan = ParsePlan(sandbox, planJson);
        var targetText = string.IsNullOrWhiteSpace(directory) ? plan.OutputDirectory : directory;
        if (string.IsNullOrWhiteSpace(targetText))
        {
            return new ToolResult(false,
                "Tool preparation needs a target directory: pass directory or set the plan's outputDirectory.");
        }

        var target = sandbox.ResolveOutput(targetText);
        var platforms = new List<string>();
        if (plan.Windows)
        {
            platforms.Add("Windows");
        }

        if (plan.Linux)
        {
            platforms.Add("Linux");
        }

        if (plan.MacOS)
        {
            platforms.Add("macOS");
        }

        var service = new DeliveryService(ToolHttpClient);
        await service.PrepareToolsAsync(
            JsonSerializer.Serialize(plan, DeliveryJsonContext.Default.DeliveryPlan),
            target,
            ToTextProgress(progress),
            cancellationToken).ConfigureAwait(false);
        var (prepared, truncated) = ListPreparedFiles(target);
        return new ToolResult(true,
            platforms.Count == 0
                ? $"Delivery plan enables no platform, so nothing was fetched into {target}."
                : $"Prepared {string.Join(", ", platforms)} tooling; {prepared.Count} file(s) under {target}"
                    + (truncated ? " (list truncated)." : "."),
            ToolJson.Data(new PreparedToolsPayload(
                target,
                platforms,
                prepared,
                truncated,
                DeliveryService.DefaultToolCacheDirectory)));
    }

    private static OtaZipVerificationPayload ToVerificationPayload(
        string path, OtaZipVerificationResult verification) =>
        new(path, verification.IsValid, verification.Errors, verification.Warnings, verification.Properties);

    private static string Summarise(IReadOnlyList<string> errors)
        => errors.Count <= 3
            ? string.Join("; ", errors)
            : string.Join("; ", errors.Take(3)) + $"; and {errors.Count - 3} more.";

    /// <summary>
    /// <para>解析并限制“ZIP 成员名到本地文件”的替换映射：值必须是沙箱内已存在的文件，键按正斜杠规范化。</para>
    /// Parses and confines the member-name to local-file replacement map: every value must be an existing file
    /// inside the sandbox and every key is normalized to forward slashes, which is how the backing service
    /// compares ZIP member names.
    /// </summary>
    private static Dictionary<string, string> ParseReplacements(PathSandbox sandbox, string? replacementsJson)
    {
        var result = new Dictionary<string, string>(StringComparer.Ordinal);
        if (string.IsNullOrWhiteSpace(replacementsJson))
        {
            return result;
        }

        var map = JsonSerializer.Deserialize(replacementsJson, McpToolJsonContext.Default.DictionaryStringString)
            ?? throw new InvalidDataException("Replacement JSON is not a string-to-string object.");
        foreach (var pair in map)
        {
            var member = pair.Key.Replace('\\', '/');
            if (member.Length == 0 || string.IsNullOrWhiteSpace(pair.Value))
            {
                throw new InvalidDataException(
                    $"Replacement entry '{pair.Key}' needs both a ZIP member name and a local file path.");
            }

            result[member] = sandbox.Resolve(pair.Value, mustExist: true);
        }

        return result;
    }

    private static string ResolveOptionalInput(PathSandbox sandbox, string path)
        => string.IsNullOrWhiteSpace(path) ? "" : sandbox.Resolve(path, mustExist: true);

    /// <summary>
    /// Parses a plan and confines its paths before the backend re-reads the serialized form.
    /// <para>解析计划并在后端重新读取序列化结果之前限制其路径。</para>
    /// The tool service consumes paths straight from the plan JSON (the local zstd overrides are read as
    /// source files), so the confined plan is re-serialized instead of passing the client text through.
    /// <para>工具服务会直接使用计划 JSON 中的路径（本地 zstd 覆盖项会作为源文件被读取），因此这里重新序列化
    /// 已受限的计划，而不是把客户端文本原样传下去。</para>
    /// Deserialization leaves each omitted section null because the plan type is built without running its
    /// initializers, so every section and collection is normalized to its empty form before confinement.
    /// <para>计划类型构造时不执行初始化器，因此 JSON 省略的节会是 null；受限之前把每一节与集合归一为空形态。</para>
    /// </summary>
    private static DeliveryPlan ParsePlan(PathSandbox sandbox, string planJson)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(planJson);
        var plan = DeliveryPlanJson.Deserialize(planJson)
            ?? throw new InvalidDataException("Delivery plan JSON could not be parsed.");
        var package = plan.Package ?? new DeliveryPackageOptions();
        var payload = plan.Payload ?? new DeliveryPayloadOptions();
        return plan with
        {
            OutputDirectory = string.IsNullOrWhiteSpace(plan.OutputDirectory)
                ? plan.OutputDirectory
                : sandbox.ResolveOutput(plan.OutputDirectory),
            Package = package with
            {
                CertificatePath = ConfineOptional(package.CertificatePath, sandbox),
                SigningKeyPath = ConfineOptional(package.SigningKeyPath, sandbox),
                RecoveryUpdaterPath = ConfineOptional(package.RecoveryUpdaterPath, sandbox)
            },
            Payload = payload with
            {
                DynamicPartitionsFile = ConfineOptional(payload.DynamicPartitionsFile, sandbox),
                SignatureFile = ConfineOptional(payload.SignatureFile, sandbox),
                SigningKeyPath = ConfineOptional(payload.SigningKeyPath, sandbox),
                PostinstallFile = ConfineOptional(payload.PostinstallFile, sandbox)
            },
            LocalZstd = (plan.LocalZstd ?? []).ToDictionary(p => p.Key, p => ConfineOptional(p.Value, sandbox) ?? string.Empty),
            Container = (plan.Container ?? []).Select(f => ConfineFile(f, sandbox)).ToList(),
            Files = (plan.Files ?? []).Select(f => ConfineFile(f, sandbox)).ToList()
        };
    }

    /// <summary>
    /// <para>限制计划内的可选路径但不要求存在：源镜像可以有意缺失，由计划校验按 <c>checkSources</c> 决定。</para>
    /// Confines an optional plan path without requiring existence, because a plan may legitimately reference a
    /// source image that is not on disk yet and plan validation decides whether that is an error.
    /// </summary>
    private static string ConfineOptional(string path, PathSandbox sandbox)
        => string.IsNullOrEmpty(path) ? path : sandbox.Resolve(path);

    private static DeliveryFile ConfineFile(DeliveryFile file, PathSandbox sandbox)
        => file with { SourcePath = string.IsNullOrEmpty(file.SourcePath) ? "" : sandbox.Resolve(file.SourcePath) };

    private static (IReadOnlyList<string> Files, bool Truncated) ListPreparedFiles(string target)
    {
        var root = Path.Combine(target, "bin");
        if (!Directory.Exists(root))
        {
            return ([], false);
        }

        var files = new List<string>();
        var truncated = false;
        foreach (var file in Directory.EnumerateFiles(root, "*", SearchOption.AllDirectories))
        {
            if (files.Count >= MaximumListedToolFiles)
            {
                truncated = true;
                break;
            }

            files.Add(Path.GetRelativePath(target, file));
        }

        return (files, truncated);
    }

    /// <summary>
    /// <para>把协议进度目标转为交付后端的文本进度接收端；没有进度令牌时返回 <see langword="null"/>，
    /// 底层实现因此不会消耗上报开销。后端的上报形如「百分比% 消息」，此处把前导百分比还原为
    /// <see cref="ProgressNotificationValue.Progress"/>。</para>
    /// Converts the protocol progress sink into the delivery backend's text-progress sink; without a progress
    /// token this returns <see langword="null"/> so the backing calls skip reporting overhead. The backend
    /// formats reports as "<c>percent% message</c>", so a leading percentage is lifted back onto
    /// <see cref="ProgressNotificationValue.Progress"/>.
    /// </summary>
    /// <param name="progress"><para>MCP 绑定的进度实例，可能为 <see langword="null"/>。</para>The MCP-bound progress instance, possibly <see langword="null"/>.</param>
    /// <returns><para>供交付后端上报进度文本的接收端。</para>A text sink for the delivery backend to report to.</returns>
    internal static IProgress<string>? ToTextProgress(IProgress<ProgressNotificationValue>? progress) =>
        progress is null
            ? null
            : new Progress<string>(text => progress.Report(ToNotification(text)));

    private static ProgressNotificationValue ToNotification(string text)
    {
        var separator = text.IndexOf('%');
        if (separator > 0
            && float.TryParse(text.AsSpan(0, separator),
                NumberStyles.AllowLeadingWhite | NumberStyles.AllowTrailingWhite | NumberStyles.AllowDecimalPoint,
                CultureInfo.InvariantCulture, out var percent))
        {
            return new ProgressNotificationValue { Progress = percent, Total = 100f, Message = text };
        }

        return new ProgressNotificationValue { Progress = 0f, Total = 100f, Message = text };
    }
}

/// <summary>
/// Reported state of one OTA ZIP verification pass.
/// <para>一次 OTA ZIP 校验的结果状态。</para>
/// </summary>
internal sealed record OtaZipVerificationPayload(
    string Path,
    bool IsValid,
    IReadOnlyList<string> Errors,
    IReadOnlyList<string> Warnings,
    IReadOnlyDictionary<string, string> Properties);

/// <summary>
/// Reported outcome of a bounded OTA ZIP member patch.
/// <para>受限 OTA ZIP 成员修补的结果。</para>
/// </summary>
internal sealed record OtaZipPatchPayload(
    string Input,
    string Output,
    IReadOnlyList<string> ReplacedEntries,
    bool OuterSignatureInvalidated,
    long OutputBytes);

/// <summary>
/// Reported outcome of an OTA rebuild around a replacement payload.
/// <para>围绕替换 payload 重建 OTA 的结果。</para>
/// </summary>
internal sealed record OtaZipRebuildPayload(
    string Input,
    string Output,
    IReadOnlyList<string> ReplacedEntries,
    bool OuterSignatureApplied,
    OtaZipVerificationPayload Verification);

/// <summary>
/// Reported outcome of a Super-to-Payload conversion.
/// <para>Super 转 Payload 的结果。</para>
/// </summary>
internal sealed record SuperPayloadConversionPayload(
    string Super,
    string Payload,
    string Properties,
    IReadOnlyList<string> Partitions,
    bool VirtualAb);

/// <summary>
/// Reported outcome of a pinned delivery tool preparation run.
/// <para>钉定版本交付工具准备的结果。</para>
/// </summary>
internal sealed record PreparedToolsPayload(
    string Target,
    IReadOnlyList<string> Platforms,
    IReadOnlyList<string> Files,
    bool Truncated,
    string ToolCache);