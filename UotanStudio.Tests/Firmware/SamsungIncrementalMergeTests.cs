/// <summary>
/// Closed-loop acceptance for the Samsung incremental-OTA merge workflow: DAT triples generated by the
/// repository's own writer are merged back against the base image and must reproduce the target bytes; slot
/// pairing, ZIP basename lookup, prism skipping, LZ4 super wrapping and deterministic failures are exercised
/// device-free. The closed-source arm64 oracle comparisons are environment-gated and skipped without a
/// persistent emulation harness.
/// <para>Samsung 增量 OTA 合并工作流的闭环验收：用本仓库写手生成的 DAT 三元组针对基座镜像回合并须复现目标字节；
/// 槽位配对、ZIP 文件名查找、prism 跳过、LZ4 super 封装与确定性失败均在无设备环境验证。
/// 闭源 arm64 oracle 对比受环境门控，在没有持久模拟桩时跳过。</para>
/// </summary>
public class SamsungIncrementalMergeTests
{
