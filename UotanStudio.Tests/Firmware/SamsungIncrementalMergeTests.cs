    private static readonly byte[] OldSystem32 = BlockPattern(0x30, 8);

    private static void WriteIncrementalTriple(string directory, string stem, byte[] source, byte[] target)
    {
        Directory.CreateDirectory(directory);
        var sourcePath = Path.Combine(directory, stem + ".old.tmp");
        var targetPath = Path.Combine(directory, stem + ".tgt.tmp");
        File.WriteAllBytes(sourcePath, source);
        File.WriteAllBytes(targetPath, target);
        DatWriter.WriteIncremental(sourcePath, targetPath,
            Path.Combine(directory, stem + ".new.dat"),
            Path.Combine(directory, stem + ".patch.dat"),
            Path.Combine(directory, stem + ".transfer.list"),
            new DatWriteOptions(), null, TestContext.Current.CancellationToken);
        File.Delete(sourcePath);
        File.Delete(targetPath);
    }

    private static byte[] BlockPattern(byte seed, int blocks)
    {
        var data = new byte[blocks * 4096];
        for (var i = 0; i < data.Length; i++)
            data[i] = (byte)(seed + i % 97);
        return data;
    }

    private static byte[] WithBlocks(byte[] source, (int Block, byte Value)[] overrides)
    {
        var data = (byte[])source.Clone();
        foreach (var (block, value) in overrides)
            for (var i = 0; i < 4096; i++)
                data[block * 4096 + i] = value;
        return data;
    }
