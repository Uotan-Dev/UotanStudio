    [Fact]
    public async Task ListPayload_MixedFullAndIncrementalPartitions_ReportsSourceFlagsAndZipContainer()
    {
        using var temp = new TempDirectory();
        using var builder = new PayloadBuilder().WithBlockSize(16);
        builder.AddPartition("system", new MemoryStream(BlockPattern(0x11, 8)));
        builder.AddPartitionIncremental("vendor",
            new MemoryStream(WithBlocks(OldSystem32, [(1, (byte)0xC1)])), new MemoryStream(OldSystem32));
        var payloadPath = Path.Combine(temp.Path, "payload.bin");
        await builder.BuildAsync(payloadPath, TestContext.Current.CancellationToken);

        var plan = await new SamsungIncrementalMergeService().ListPayloadAsync(payloadPath,
            TestContext.Current.CancellationToken);

        Assert.Equal(16u, plan.BlockSize);
        Assert.Collection(plan.Partitions.OrderBy(partition => partition.PartitionName, StringComparer.Ordinal),
            partition =>
            {
                Assert.Equal("system", partition.PartitionName);
                Assert.False(partition.RequiresSourceImages);
                Assert.Equal(32768, partition.NewSizeBytes);
            },
            partition =>
            {
                Assert.Equal("vendor", partition.PartitionName);
                Assert.True(partition.RequiresSourceImages);
                Assert.True(partition.OperationCount > 0);
            });

        var zipPath = Path.Combine(temp.Path, "ota.zip");
        using (var archive = ZipFile.Open(zipPath, ZipArchiveMode.Create))
            archive.CreateEntryFromFile(payloadPath, "payload.bin", CompressionLevel.NoCompression);
        var zipPlan = await new SamsungIncrementalMergeService().ListPayloadAsync(zipPath,
            TestContext.Current.CancellationToken);
        Assert.Equal(plan.Partitions.Count, zipPlan.Partitions.Count);
    }

