    [Fact]
    public async Task MergeDat_LooseSlotSuffixedTriple_PairsBaseAfterSlotStripAndReproducesTarget()
    {
        using var temp = new TempDirectory();
        var tripleDirectory = Path.Combine(temp.Path, "ota");
        WriteIncrementalTriple(tripleDirectory, "system_a", OldSystem, NewSystem);
        var basePath = temp.WriteBytes("system.img", OldSystem);
        var output = Path.Combine(temp.Path, "merged");
        var hookNames = new List<string>();
        var options = new SamsungIncrementalMergeOptions
        {
            OnPartitionMerged = (image, _) =>
            {
                hookNames.Add(image.PartitionName);
                return Task.CompletedTask;
            },
        };

        var result = await new SamsungIncrementalMergeService().MergeDatAsync(basePath, tripleDirectory, output,
            options, cancellationToken: TestContext.Current.CancellationToken);

        var merged = Assert.Single(result.MergedPartitions);
        Assert.Equal("system", merged.PartitionName);
        Assert.Equal(NewSystem, File.ReadAllBytes(merged.OutputImagePath));
        Assert.Equal("system", Assert.Single(hookNames));
        Assert.Empty(result.SkippedPartitions);
    }

    [Fact]
    public async Task MergeDat_ZippedTriplesUnderDirectoryPrefix_LocatesByBasenameAndSkipsPrism()
    {
        using var temp = new TempDirectory();
        var corpus = Path.Combine(temp.Path, "corpus");
        WriteIncrementalTriple(corpus, "system_a", OldSystem, NewSystem);
        WriteIncrementalTriple(corpus, "prism_a", OldSystem, NewSystem);
        var zipPath = Path.Combine(temp.Path, "ota.zip");
        using (var archive = ZipFile.Open(zipPath, ZipArchiveMode.Create))
        {
            archive.CreateEntryFromFile(Path.Combine(corpus, "system_a.transfer.list"),
                "S-M9750/SYSTEM/system_a.transfer.list");
            archive.CreateEntryFromFile(Path.Combine(corpus, "system_a.new.dat"), "S-M9750/SYSTEM/system_a.new.dat");
            archive.CreateEntryFromFile(Path.Combine(corpus, "system_a.patch.dat"), "S-M9750/SYSTEM/system_a.patch.dat");
            archive.CreateEntryFromFile(Path.Combine(corpus, "prism_a.transfer.list"), "S-M9750/PRISM/prism_a.transfer.list");
            archive.CreateEntryFromFile(Path.Combine(corpus, "prism_a.new.dat"), "S-M9750/PRISM/prism_a.new.dat");
            archive.CreateEntryFromFile(Path.Combine(corpus, "prism_a.patch.dat"), "S-M9750/PRISM/prism_a.patch.dat");
        }

        var basePath = temp.WriteBytes("system.img", OldSystem);
        var output = Path.Combine(temp.Path, "merged");
        var result = await new SamsungIncrementalMergeService().MergeDatAsync(basePath, zipPath, output,
            cancellationToken: TestContext.Current.CancellationToken);

        var merged = Assert.Single(result.MergedPartitions);
        Assert.Equal("system", merged.PartitionName);
        Assert.Equal(NewSystem, File.ReadAllBytes(merged.OutputImagePath));
        Assert.Contains("prism_a", result.SkippedPartitions, StringComparer.Ordinal);
        Assert.False(File.Exists(Path.Combine(output, "prism.img")));
        Assert.Empty(Directory.EnumerateFiles(output, "prism*"));
    }

