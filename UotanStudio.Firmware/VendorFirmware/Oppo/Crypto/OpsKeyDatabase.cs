    /// <param name="keyId">Key identifier such as <c>mbox5</c>; matched case-insensitively. A <see langword="null"/> value simply yields no match.
    /// <para> 形如 <c>mbox5</c> 的密钥标识符；按不区分大小写匹配。传入 <see langword="null"/> 时只会匹配失败。 </para></param>
    /// <returns>The matching entry, or <see langword="null"/> when the identifier is unknown.
    /// <para>匹配的条目；标识符未知时返回 <see langword="null"/>。</para></returns>
    public static OpsKeyEntry? FindByKeyId(string keyId)
    {
        foreach (var entry in KeyEntries)
        {
            if (string.Equals(entry.KeyId, keyId, StringComparison.OrdinalIgnoreCase))
            {
                return entry;
            }
        }

        return null;
    }

    private static byte[] GenerateExpandedSBox()
    {
        var result = new byte[2048];
        for (var i = 0; i < 256; i++)
        {
            var s = AesSBoxInner[i];
            var te0 = ((uint)Mul2(s) << 24) | ((uint)s << 16) | ((uint)s << 8) | Mul3(s);


            result[(i * 8) + 0] = (byte)(te0 >> 24);
            result[(i * 8) + 1] = (byte)(te0 >> 16);
            result[(i * 8) + 2] = (byte)(te0 >> 8);
            result[(i * 8) + 3] = (byte)(te0 >> 0);
            result[(i * 8) + 4] = (byte)(te0 >> 24);
            result[(i * 8) + 5] = (byte)(te0 >> 16);
            result[(i * 8) + 6] = (byte)(te0 >> 8);
            result[(i * 8) + 7] = (byte)(te0 >> 0);
        }

        return result;
    }

    private static byte Mul2(byte b) => (byte)((b << 1) ^ ((b & 0x80) != 0 ? 0x1b : 0x00));

    private static byte Mul3(byte b) => (byte)(Mul2(b) ^ b);
