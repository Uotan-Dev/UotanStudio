namespace UotanStudio.Firmware.HarmonyMeta.Hap;

/// <summary>
/// Byte-level constants of the OpenHarmony/HarmonyOS HAP signing scheme, calibrated against the official
/// <c>hap-sign-tool</c> output and the on-device verifier layout.
/// <para>OpenHarmony/HarmonyOS HAP 签名方案的字节级常量，依据官方 <c>hap-sign-tool</c> 产物与设备端验签布局标定。</para>
/// </summary>
/// <remarks>
/// The signing block sits immediately before the ZIP central directory and ends exactly where the central directory
/// begins. Its trailing <c>u64</c> size counts the TLV headers, the value region, the <c>u32</c> block count, the
/// <c>u64</c> size field itself, the 16-byte magic and the trailing <c>u32</c> version — 28 bytes of fixed tail.
/// <para>签名块紧贴 ZIP 中央目录之前并恰好结束于中央目录起点。块尾 <c>u64</c> 总长计入 TLV 头、值区、
/// <c>u32</c> 块数、<c>u64</c> 长度字段自身、16 字节魔数与末尾 <c>u32</c> 版本——固定尾部共 28 字节。</para>
/// </remarks>
internal static class HapSignatureConstants
{
    /// <summary>Main CMS SignedData block. <para>主 CMS SignedData 块。</para></summary>
    internal const uint BlockIdSignature = 0x20000000;

    /// <summary>Proof-of-rotation certificate chain block (never generated by the official tool).
    /// <para>证书轮换链块（官方工具不生成）。</para></summary>
    internal const uint BlockIdProofOfRotation = 0x20000001;

    /// <summary>Embedded <c>.p7b</c> provisioning profile block. <para>内嵌 <c>.p7b</c> Profile 块。</para></summary>
    internal const uint BlockIdProfile = 0x20000002;

    /// <summary>Build property metadata block. <para>构建属性元数据块。</para></summary>
    internal const uint BlockIdProperty = 0x20000003;

    /// <summary>Code signing block ID stored inside the property block value.
    /// <para>存于 property 块值内部的代码签名块 ID。</para></summary>
    internal const uint BlockIdCodeSign = 0x30000001;

    /// <summary>Signing block magic for <c>compatibleSdkVersion &lt; 8</c> (scheme version 2).
    /// <para><c>compatibleSdkVersion &lt; 8</c>（方案版本 2）的签名块魔数。</para></summary>
    internal static readonly byte[] MagicV2 = "HAP Sig Block 42"u8.ToArray();

    /// <summary>Signing block magic for <c>compatibleSdkVersion &gt;= 8</c> (scheme version 3).
    /// <para><c>compatibleSdkVersion &gt;= 8</c>（方案版本 3）的签名块魔数。</para></summary>
    internal static readonly byte[] MagicV3 = "<hap sign block>"u8.ToArray();

    /// <summary>Scheme version emitted for <c>compatibleSdkVersion &lt; 8</c>.
    /// <para><c>compatibleSdkVersion &lt; 8</c> 产出的方案版本。</para></summary>
    internal const uint SchemeVersionV2 = 2;

    /// <summary>Scheme version emitted for <c>compatibleSdkVersion &gt;= 8</c>.
    /// <para><c>compatibleSdkVersion &gt;= 8</c> 产出的方案版本。</para></summary>
    internal const uint SchemeVersionV3 = 3;

    /// <summary>The <c>compatibleSdkVersion</c> boundary between scheme versions 2 and 3.
    /// <para>方案版本 2 与 3 之间的 <c>compatibleSdkVersion</c> 分界。</para></summary>
    internal const uint SchemeVersionBoundary = 8;

    /// <summary>ECDSA P-256 with SHA-256. <para>ECDSA P-256 + SHA-256。</para></summary>
    internal const uint AlgorithmEcdsaSha256 = 0x201;

    /// <summary>ECDSA with SHA-384. <para>ECDSA + SHA-384。</para></summary>
    internal const uint AlgorithmEcdsaSha384 = 0x202;

    /// <summary>ECDSA with SHA-512. <para>ECDSA + SHA-512。</para></summary>
    internal const uint AlgorithmEcdsaSha512 = 0x203;

    /// <summary>RSA-PSS with SHA-256. <para>RSA-PSS + SHA-256。</para></summary>
    internal const uint AlgorithmRsaPssSha256 = 0x101;

    /// <summary>RSA-PSS with SHA-384. <para>RSA-PSS + SHA-384。</para></summary>
    internal const uint AlgorithmRsaPssSha384 = 0x102;

    /// <summary>RSA-PSS with SHA-512. <para>RSA-PSS + SHA-512。</para></summary>
    internal const uint AlgorithmRsaPssSha512 = 0x103;

    /// <summary>Digest chunk size: 1 MiB. <para>摘要分块大小：1 MiB。</para></summary>
    internal const int DigestChunkSize = 1 << 20;

    /// <summary>First-level digest type prefix byte. <para>摘要一级类型前缀字节。</para></summary>
    internal const byte DigestTopPrefix = 0x5a;

    /// <summary>Per-chunk digest type prefix byte. <para>每块摘要的类型前缀字节。</para></summary>
    internal const byte DigestChunkPrefix = 0xa5;

    /// <summary>Digest message version field. <para>摘要消息版本字段。</para></summary>
    internal const uint DigestMessageVersion = 2;

    /// <summary>Alignment applied to the first entry's data and to stored runnable/bitmap entries.
    /// <para>首条目数据与 stored 的 runnable/bitmap 条目使用的对齐。</para></summary>
    internal const int AlignmentPage = 4096;

    /// <summary>Alignment applied to subsequent stored entries. <para>后续 stored 条目使用的对齐。</para></summary>
    internal const int AlignmentNormal = 4;
}