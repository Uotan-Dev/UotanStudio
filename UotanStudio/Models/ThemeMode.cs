namespace UotanStudio.Models;

/// <summary>
/// Theme mode enum, defining the available theme options for the application.
/// <para>主题模式枚举，定义应用程序可用的主题选项。</para>
/// </summary>
public enum ThemeMode
{
    /// <summary>
    /// Follow the system theme.
    /// <para>跟随系统主题。</para>
    /// </summary>
    System = 0,

    /// <summary>
    /// Light theme.
    /// <para>浅色主题。</para>
    /// </summary>
    Light = 1,

    /// <summary>
    /// Dark theme.
    /// <para>深色主题。</para>
    /// </summary>
    Dark = 2
}