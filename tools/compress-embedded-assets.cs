#:property ManagePackageVersionsCentrally=false
#:package ZstdSharp.Port@0.8.8

using System.Security.Cryptography;
using System.Text;
using ZstdSharp;

const int Level = 19;

var root = FindRepositoryRoot();
var failures = 0;

var fonts = new (string Source, string Target)[]
{
    (FindFontSource(root, "MiSans-Regular.ttf"), Path.Combine(root, "UotanStudio", "Fonts", "MiSans-Regular.ttf.zst")),
    (FindFontSource(root, "MiSans-Bold.ttf"), Path.Combine(root, "UotanStudio", "Fonts", "MiSans-Bold.ttf.zst")),
};

foreach (var (source, target) in fonts)
{
    failures += Compress(source, target) ? 0 : 1;
}

var deviceDirectory = Path.Combine(root, "UotanStudio.Mirroring", "Assets", "ohos", "device");
var manifest = new StringBuilder();
manifest.AppendLine("# Generated by tools/compress-embedded-assets.cs; do not edit by hand.");
manifest.AppendLine("# <fileName>\t<uncompressedLength>\t<lowercase sha256>");
foreach (var file in Directory.EnumerateFiles(deviceDirectory, "*.so").OrderBy(path => Path.GetFileName(path), StringComparer.Ordinal))
{
    if (!Compress(file, file + ".zst"))
    {
        failures++;
        continue;
    }

    var length = new FileInfo(file).Length;
    manifest.Append(Path.GetFileName(file)).Append('\t').Append(length).Append('\t').AppendLine(Sha256(file));
}

var manifestPath = Path.Combine(deviceDirectory, "manifest.txt");
File.WriteAllText(manifestPath, manifest.ToString(), new UTF8Encoding(false));
Console.WriteLine($"wrote {Relative(root, manifestPath)}");

failures += Compress(
    Path.Combine(root, "UotanStudio.Delivery", "Assets", "update-binary-arm64"),
    Path.Combine(root, "UotanStudio.Delivery", "Assets", "update-binary-arm64.zst")) ? 0 : 1;

Console.WriteLine(failures == 0 ? "asset compression: OK" : $"asset compression: {failures} failure(s)");
return failures == 0 ? 0 : 1;

static string FindFontSource(string root, string fileName)
{
    string[] candidates =
    [
        Path.Combine(root, "UotanStudio", "Assets", "Fonts", fileName),
        Path.Combine(root, "reference", "fonts-source", fileName),
    ];
    foreach (var candidate in candidates)
    {
        if (File.Exists(candidate))
        {
            return candidate;
        }
    }

    return candidates[0];
}

static string FindRepositoryRoot(){
    var directory = new DirectoryInfo(Environment.CurrentDirectory);
    while (directory is not null)
    {
        if (File.Exists(Path.Combine(directory.FullName, "UotanStudio.slnx")))
        {
            return directory.FullName;
        }

        directory = directory.Parent;
    }

    throw new InvalidOperationException("Run this script from inside the UotanStudio repository (UotanStudio.slnx not found).");
}

static bool Compress(string source, string target)
{
    if (!File.Exists(source))
    {
        Console.Error.WriteLine($"missing source: {source}");
        return false;
    }

    var data = File.ReadAllBytes(source);
    var compressed = new Compressor(Level).Wrap(data).ToArray();
    Directory.CreateDirectory(Path.GetDirectoryName(target)!);
    File.WriteAllBytes(target, compressed);
    var roundTrip = new Decompressor().Unwrap(compressed).ToArray();
    if (!roundTrip.AsSpan().SequenceEqual(data))
    {
        Console.Error.WriteLine($"round trip mismatch: {source}");
        return false;
    }

    Console.WriteLine($"{Path.GetFileName(source),-40} {data.Length,10:N0} -> {compressed.Length,10:N0} ({compressed.Length * 100.0 / data.Length,5:F1}%)");
    return true;
}

static string Sha256(string path)
{
    using var stream = File.OpenRead(path);
    return Convert.ToHexStringLower(SHA256.HashData(stream));
}

static string Relative(string root, string path) => Path.GetRelativePath(root, path);
