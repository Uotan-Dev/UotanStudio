using System.Text;
using UotanStudio.Firmware.MagicGen;
using UotanStudio.Firmware.SharedKernel.Magic;

// Build-time code generator: converts the vendored upstream file(1) magic(5) corpus into a compiled
// C# rule table consumed by UotanStudio.Firmware's CompiledMagicEngine at runtime.
// Usage: dotnet run --project UotanStudio.Firmware.MagicGen [corpusDir] [outputCs]
//        dotnet run --project UotanStudio.Firmware.MagicGen -- --smoke

if (args.Length > 0 && args[0] == "--smoke")
{
    return SmokeTest();
}

if (args.Length > 1 && args[0] == "--files")
{
    int rc = 0;
    foreach (string p in args[1..])
    {
        var info = FileMagic.IdentifyFile(p);
        Console.WriteLine($"{Path.GetFileName(p),-16} => {(info is null ? "<null>" : $"{info.Description} | mime={info.MimeType ?? "-"} | ext={info.Extensions ?? "-"}")}");
        rc = info is null ? rc : rc;
    }

    return 0;
}

string repoRoot = FindRepoRoot() ?? Directory.GetCurrentDirectory();
string corpusDir = args.Length > 0 ? args[0] : Path.Combine(repoRoot, "UotanStudio.Firmware.MagicGen", "corpus");
string outputCs = args.Length > 1 ? args[1] : Path.Combine(repoRoot, "UotanStudio.Firmware", "SharedKernel", "Magic", "Generated", "CompiledMagicData.g.cs");

string manifest = Path.Combine(corpusDir, "LOAD_ORDER.txt");
if (!File.Exists(manifest))
{
    Console.Error.WriteLine($"Missing manifest: {manifest}");
    return 2;
}

var parser = new Magic5Parser();
var all = new List<RuleAst>();
int fragmentCount = 0;
int missing = 0;

foreach (string raw in File.ReadLines(manifest))
{
    string rel = raw.Trim();
    if (rel.Length == 0 || rel.StartsWith('#'))
    {
        continue;
    }

    string path = Path.Combine(corpusDir, rel.Replace('/', Path.DirectorySeparatorChar));
    if (!File.Exists(path))
    {
        missing++;
        continue;
    }

    string text = File.ReadAllText(path, new UTF8Encoding(false));
    parser.CurrentSource = rel;
    all.AddRange(parser.ParseFragment(text));
    fragmentCount++;
}

var (blob, topLevel) = Emitter.Emit(all);
string b64 = Convert.ToBase64String(blob);

var sb = new StringBuilder();
sb.AppendLine("// <auto-generated/>");
sb.AppendLine("// Generated by UotanStudio.Firmware.MagicGen from the vendored upstream file(1) magic(5) corpus.");
sb.AppendLine("// Do not edit by hand. Re-generate with: dotnet run --project UotanStudio.Firmware.MagicGen");
sb.AppendLine("using System;");
sb.AppendLine();
sb.AppendLine("#nullable enable");
sb.AppendLine();
sb.AppendLine("namespace UotanStudio.Firmware.SharedKernel.Magic;");
sb.AppendLine();
sb.AppendLine("/// <summary>生成器产出的编译型规则表。</summary>");
sb.AppendLine("public static partial class CompiledMagicData");
sb.AppendLine("{");
sb.AppendLine($"    /// <summary>生成时间戳。 / Generation timestamp.</summary>");
sb.AppendLine($"    public const string GeneratedAt = \"{DateTime.UtcNow:yyyy-MM-dd HH:mm:ss}Z\";");
sb.AppendLine();
sb.AppendLine($"    /// <summary>顶层规则数。 / Top-level rule count.</summary>");
sb.AppendLine($"    public const int RuleCount = {topLevel};");
sb.AppendLine();
sb.AppendLine("    private const int BlobByteLength = " + blob.Length + ";");
sb.AppendLine();
sb.AppendLine("    private static readonly string[] Parts =");
sb.AppendLine("    {");
const int chunk = 16000; // multiple of 4 → each decodes independently
for (int i = 0; i < b64.Length; i += chunk)
{
    int len = Math.Min(chunk, b64.Length - i);
    len -= len % 4;
    if (len <= 0)
    {
        len = Math.Min(chunk, b64.Length - i);
    }

    sb.Append("        \"");
    sb.Append(b64, i, len);
    sb.AppendLine("\",");
}

sb.AppendLine("    };");
sb.AppendLine();
sb.AppendLine("    private static byte[]? _rules;");
sb.AppendLine();
sb.AppendLine("    /// <summary>序列化规则表字节。 / Serialized rule-table bytes.</summary>");
sb.AppendLine("    public static byte[] Rules => _rules ??= Decode();");
sb.AppendLine();
sb.AppendLine("    private static byte[] Decode()");
sb.AppendLine("    {");
sb.AppendLine("        int total = 0;");
sb.AppendLine("        foreach (var p in Parts)");
sb.AppendLine("        {");
sb.AppendLine("            total += (p.Length / 4) * 3;");
sb.AppendLine("        }");
sb.AppendLine();
sb.AppendLine("        var buf = new byte[total];");
sb.AppendLine("        int written = 0;");
sb.AppendLine("        foreach (var p in Parts)");
sb.AppendLine("        {");
sb.AppendLine("            var b = Convert.FromBase64String(p);");
sb.AppendLine("            Buffer.BlockCopy(b, 0, buf, written, b.Length);");
sb.AppendLine("            written += b.Length;");
sb.AppendLine("        }");
sb.AppendLine();
sb.AppendLine("        Array.Resize(ref buf, written);");
sb.AppendLine("        return buf;");
sb.AppendLine("    }");
sb.AppendLine("}");

Directory.CreateDirectory(Path.GetDirectoryName(outputCs)!);
File.WriteAllText(outputCs, sb.ToString(), new UTF8Encoding(false));

var s = parser.Statistics;
Console.WriteLine($"fragments={fragmentCount} missing={missing}");
Console.WriteLine($"rules={s.Rules} annotations={s.Annotations} topLevel={topLevel}");
Console.WriteLine($"blob={blob.Length} bytes, base64={b64.Length} chars");
Console.WriteLine($"skipped: range={s.SkippedRange} der={s.SkippedDer} indirect={s.SkippedIndirectKeyword} transform={s.SkippedTransform} unknownType={s.SkippedUnknownType} malformed={s.SkippedMalformed}");
Console.WriteLine("top unknown types:");
foreach (var kv in Descending(s.UnknownTypes).Take(20))
{
    Console.WriteLine($"  {kv.Key} = {kv.Value}");
}

Console.WriteLine($"wrote {outputCs}");
return 0;

static IEnumerable<KeyValuePair<string, int>> Descending(Dictionary<string, int> d)
{
    var list = new List<KeyValuePair<string, int>>(d);
    list.Sort((a, b) => b.Value.CompareTo(a.Value));
    return list;
}

static int SmokeTest()
{
    Console.WriteLine($"top-level rules loaded: {FileMagic.Identify(new byte[] { 0x89, 0x50, 0x4E, 0x47 }) is not null}");
    var samples = new (string Name, byte[] Data)[]
    {
        ("PNG", [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x02, 0x00, 0x00, 0x00, 0x90, 0x77, 0x53, 0xDE]),
        ("GZIP", [0x1F, 0x8B, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xFF, 0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00]),
        ("ZIP", [0x50, 0x4B, 0x03, 0x04, 0x14, 0x00, 0x06, 0x00, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00]),
        ("ELF64", [.. new byte[] { 0x7F, 0x45, 0x4C, 0x46, 0x02, 0x01, 0x01, 0x00 }, .. new byte[57]]),
        ("PDF", "25 50 44 46 2D 31 2E 34 0A".Split(' ').Select(x => Convert.ToByte(x, 16)).ToArray()),
        ("WAV", [0x52, 0x49, 0x46, 0x46, 0x24, 0x00, 0x00, 0x00, 0x57, 0x41, 0x56, 0x45, 0x66, 0x6D, 0x74, 0x20]),
        ("GIF", "47 49 46 38 39 61 01 00 01 00 80 00 00".Split(' ').Select(x => Convert.ToByte(x, 16)).ToArray()),
        ("plain-text", "Hello, this is a plain text file with words.\n"u8.ToArray()),
        ("empty", []),
        ("ELF-aarch64", Elf(elf64: true, be: false, machine: 0xB7, type: 2)),
        ("ELF-riscv64", Elf(elf64: true, be: false, machine: 0xF3, type: 3)),
        ("AndroidBoot", "ANDROID!"u8.ToArray()),
        ("VendorBoot", "VNDRBOOT"u8.ToArray()),
        ("Dtbo", "DTBO"u8.ToArray()),
        ("Payload", "CrAU"u8.ToArray()),
        ("Avb", "AVBf"u8.ToArray()),
        ("FDT", [0xD0, 0x0D, 0xFE, 0xED, 0x00, 0x00]),
        ("XZ", [0xFD, 0x37, 0x7A, 0x58, 0x5A, 0x00]),
        ("ZSTD", [0x28, 0xB5, 0x2F, 0xFD, 0x20, 0x05]),
        ("LZ4F", [0x04, 0x22, 0x4D, 0x18, 0x64, 0x70]),
        ("Sparse", [0x3A, 0xFF, 0x26, 0xED, 0x10, 0x00, 0x00, 0x00, 0x00, 0x10, 0x00, 0x00, 0x0C, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00]),
        ("CpioNewc", "070701"u8.ToArray()),
        ("RKFW", "RKFW"u8.ToArray()),
    };

    static byte[] Elf(bool elf64, bool be, int machine, int type)
    {
        byte[] h = new byte[64];
        h[0] = 0x7F; h[1] = (byte)'E'; h[2] = (byte)'L'; h[3] = (byte)'F';
        h[4] = (byte)(elf64 ? 2 : 1);
        h[5] = (byte)(be ? 2 : 1);
        h[6] = 1;
        h[7] = 0;
        void Put(int off, int val)
        {
            if (be) { h[off] = (byte)(val >> 8); h[off + 1] = (byte)val; }
            else { h[off] = (byte)val; h[off + 1] = (byte)(val >> 8); }
        }

        Put(16, type);
        Put(18, machine);
        return h;
    }

    int ok = 0;
    foreach (var (name, data) in samples)
    {
        if (name == "PNG" || name == "GZIP" || name == "ZIP")
        {
            CompiledMagicEngine.DebugMatch = true;
            CompiledMagicEngine.DebugMatches.Clear();
        }

        var info = FileMagic.Identify(data);
        Console.WriteLine($"  {name,-11} => {(info is null ? "<null>" : $"{info.Description} | mime={info.MimeType ?? "-"} | ext={info.Extensions ?? "-"}")}");
        if (name == "PNG" || name == "GZIP" || name == "ZIP")
        {
            foreach (var d in CompiledMagicEngine.DebugMatches)
            {
                Console.WriteLine($"      DBG {d}");
            }

            CompiledMagicEngine.DebugMatch = false;
        }

        if (info is not null)
        {
            ok++;
        }
    }

    Console.WriteLine($"smoke: {ok}/{samples.Length} samples matched (plain-text/empty may be null)");
    return 0;
}

static string? FindRepoRoot()
{
    var dir = new DirectoryInfo(AppContext.BaseDirectory);
    while (dir is not null)
    {
        if (File.Exists(Path.Combine(dir.FullName, "UotanStudio.slnx")))
        {
            return dir.FullName;
        }

        dir = dir.Parent;
    }

    return null;
}
