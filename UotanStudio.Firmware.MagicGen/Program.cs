using System.Globalization;
using System.Text;
using UotanStudio.Compress.Codecs.Zstd;
using UotanStudio.Firmware.Core.Magic;
using UotanStudio.Firmware.MagicGen;
using UotanStudio.Hash.Digests;

if (args.Length > 0 && args[0] == "--smoke")
{
    return SmokeTest();
}

if (args.Length > 1 && args[0] == "--files")
{
    var rc = 0;
    foreach (var p in args[1..])
    {
        var info = FileMagic.IdentifyFile(p);
        Console.WriteLine($"{Path.GetFileName(p),-16} => {(info is null ? "<null>" : $"{info.Description} | mime={info.MimeType ?? "-"} | ext={info.Extensions ?? "-"}")}");
        rc = info is null ? rc : rc;
    }

    return 0;
}

var repoRoot = FindRepoRoot() ?? Directory.GetCurrentDirectory();
var corpusDir = args.Length > 0 ? args[0] : Path.Combine(repoRoot, "UotanStudio.Firmware.MagicGen", "corpus");
var outputCs = args.Length > 1 ? args[1] : Path.Combine(repoRoot, "UotanStudio.Firmware", "Core", "Magic", "Generated", "CompiledMagicData.g.cs");

var manifest = Path.Combine(corpusDir, "LOAD_ORDER.txt");
if (!File.Exists(manifest))
{
    Console.Error.WriteLine($"Missing manifest: {manifest}");
    return 2;
}

var parser = new Magic5Parser();
var all = new List<RuleAst>();
var fragmentCount = 0;
var missing = 0;

foreach (var raw in File.ReadLines(manifest))
{
    var rel = raw.Trim();
    if (rel.Length == 0 || rel.StartsWith('#'))
    {
        continue;
    }

    var path = Path.Combine(corpusDir, rel.Replace('/', Path.DirectorySeparatorChar));
    if (!File.Exists(path))
    {
        missing++;
        continue;
    }

    var text = File.ReadAllText(path, new UTF8Encoding(false));
    parser.CurrentSource = rel;
    all.AddRange(parser.ParseFragment(text));
    fragmentCount++;
}

var (blob, topLevel) = Emitter.Emit(all);

const int RulesCompressionLevel = 19;
var compressed = new byte[ZstdBlockCodec.MaximumCompressedSize(blob.Length)];
var compressedLength = ZstdBlockCodec.Compress(blob, compressed, level: RulesCompressionLevel);
var rulesSha256 = Sha256.ComputeHexLower(blob);
var generatedAt = DateTime.UtcNow.ToString("yyyy-MM-dd HH:mm:ss", CultureInfo.InvariantCulture) + "Z";

var outputDirectory = Path.GetDirectoryName(outputCs) ?? Directory.GetCurrentDirectory();
var outputBlob = Path.Combine(outputDirectory, "CompiledMagicData.zst");

var sb = new StringBuilder();
sb.AppendLine("// <auto-generated/>");
sb.AppendLine("// Generated by UotanStudio.Firmware.MagicGen from the magic(5) type-identification rules.");
sb.AppendLine("// Do not edit by hand. Re-generate with: dotnet run --project UotanStudio.Firmware.MagicGen");
sb.AppendLine("// The rule table ships beside this file as CompiledMagicData.zst and is decoded on first use.");
sb.AppendLine();
sb.AppendLine("#nullable enable");
sb.AppendLine();
sb.AppendLine("namespace UotanStudio.Firmware.Core.Magic.Generated;");
sb.AppendLine();
sb.AppendLine("/// <summary>Metadata for the generated compiled magic rule table. <para>生成器产出的编译型规则表元数据。</para></summary>");
sb.AppendLine("internal static partial class CompiledMagicData");
sb.AppendLine("{");
sb.AppendLine("    /// <summary>Generation timestamp in ISO-8601 UTC. <para>生成时间戳（ISO-8601 UTC）。</para></summary>");
sb.AppendLine($"    internal const string GeneratedAt = \"{generatedAt}\";");
sb.AppendLine();
sb.AppendLine("    /// <summary>Number of top-level rules in the table. <para>规则表的顶层规则数。</para></summary>");
sb.AppendLine($"    internal const int RuleCount = {topLevel};");
sb.AppendLine();
sb.AppendLine("    /// <summary>Decoded byte length of the serialized rule table. <para>序列化规则表解码后的字节长度。</para></summary>");
sb.AppendLine($"    internal const int RulesByteLength = {blob.Length};");
sb.AppendLine();
sb.AppendLine("    /// <summary>Byte length of the embedded zstd frame. <para>内嵌 zstd 帧的字节长度。</para></summary>");
sb.AppendLine($"    internal const int CompressedByteLength = {compressedLength};");
sb.AppendLine();
sb.AppendLine("    /// <summary>Lower-case SHA-256 of the decoded rule table. <para>解码后规则表的小写 SHA-256。</para></summary>");
sb.AppendLine($"    internal const string RulesSha256 = \"{rulesSha256}\";");
sb.AppendLine("}");

Directory.CreateDirectory(outputDirectory);
using (var binary = File.Create(outputBlob))
{
    binary.Write(compressed, 0, compressedLength);
}

File.WriteAllText(outputCs, sb.ToString(), new UTF8Encoding(false));

var s = parser.Statistics;
Console.WriteLine($"fragments={fragmentCount} missing={missing}");
Console.WriteLine($"rules={s.Rules} annotations={s.Annotations} topLevel={topLevel}");
Console.WriteLine($"blob={blob.Length} bytes, zstd={compressedLength} bytes ({(double)compressedLength * 100 / blob.Length:F1}%), sha256={rulesSha256}");
Console.WriteLine($"skipped: range={s.SkippedRange} der={s.SkippedDer} indirect={s.SkippedIndirectKeyword} transform={s.SkippedTransform} unknownType={s.SkippedUnknownType} malformed={s.SkippedMalformed}");
Console.WriteLine("top unknown types:");
foreach (var kv in Descending(s.UnknownTypes).Take(20))
{
    Console.WriteLine($"  {kv.Key} = {kv.Value}");
}

Console.WriteLine($"wrote {outputCs}");
Console.WriteLine($"wrote {outputBlob}");
return 0;

static IEnumerable<KeyValuePair<string, int>> Descending(Dictionary<string, int> d)
{
    var list = new List<KeyValuePair<string, int>>(d);
    list.Sort((a, b) => b.Value.CompareTo(a.Value));
    return list;
}

static int SmokeTest()
{
    Console.WriteLine($"top-level rules loaded: {FileMagic.Identify([0x89, 0x50, 0x4E, 0x47]) is not null}");
    (string Name, byte[] Data)[] samples =
    [
        ("PNG", [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x02, 0x00, 0x00, 0x00, 0x90, 0x77, 0x53, 0xDE]),
        ("GZIP", [0x1F, 0x8B, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xFF, 0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00]),
        ("ZIP", [0x50, 0x4B, 0x03, 0x04, 0x14, 0x00, 0x06, 0x00, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00]),
        ("ELF64", [0x7F, 0x45, 0x4C, 0x46, 0x02, 0x01, 0x01, 0x00, .. new byte[57]]),
        ("PDF", "%PDF-1.4\n"u8.ToArray()),
        ("WAV", [0x52, 0x49, 0x46, 0x46, 0x24, 0x00, 0x00, 0x00, 0x57, 0x41, 0x56, 0x45, 0x66, 0x6D, 0x74, 0x20]),
        ("GIF", [0x47, 0x49, 0x46, 0x38, 0x39, 0x61, 0x01, 0x00, 0x01, 0x00, 0x80, 0x00, 0x00]),
        ("plain-text", "Hello, this is a plain text file with words.\n"u8.ToArray()),
        ("empty", []),
        ("ELF-aarch64", Elf(elf64: true, be: false, machine: 0xB7, type: 2)),
        ("ELF-riscv64", Elf(elf64: true, be: false, machine: 0xF3, type: 3)),
        ("AndroidBoot", "ANDROID!"u8.ToArray()),
        ("VendorBoot", "VNDRBOOT"u8.ToArray()),
        ("Dtbo", "DTBO"u8.ToArray()),
        ("Payload", "CrAU"u8.ToArray()),
        ("Avb", "AVBf"u8.ToArray()),
        ("FDT", [0xD0, 0x0D, 0xFE, 0xED, 0x00, 0x00]),
        ("XZ", [0xFD, 0x37, 0x7A, 0x58, 0x5A, 0x00]),
        ("ZSTD", [0x28, 0xB5, 0x2F, 0xFD, 0x20, 0x05]),
        ("LZ4F", [0x04, 0x22, 0x4D, 0x18, 0x64, 0x70]),
        ("Sparse", [0x3A, 0xFF, 0x26, 0xED, 0x10, 0x00, 0x00, 0x00, 0x00, 0x10, 0x00, 0x00, 0x0C, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00]),
        ("CpioNewc", "070701"u8.ToArray()),
        ("RKFW", "RKFW"u8.ToArray()),
    ];

    static byte[] Elf(bool elf64, bool be, int machine, int type)
    {
        var h = new byte[64];
        h[0] = 0x7F; h[1] = (byte)'E'; h[2] = (byte)'L'; h[3] = (byte)'F';
        h[4] = (byte)(elf64 ? 2 : 1);
        h[5] = (byte)(be ? 2 : 1);
        h[6] = 1;
        h[7] = 0;
        void Put(int off, int val)
        {
            if (be) { h[off] = (byte)(val >> 8); h[off + 1] = (byte)val; }
            else { h[off] = (byte)val; h[off + 1] = (byte)(val >> 8); }
        }

        Put(16, type);
        Put(18, machine);
        return h;
    }

    var ok = 0;
    foreach (var (name, data) in samples)
    {
        if (name == "PNG" || name == "GZIP" || name == "ZIP")
        {
            CompiledMagicEngine.DebugMatch = true;
            CompiledMagicEngine.DebugMatches.Clear();
        }

        var info = FileMagic.Identify(data);
        Console.WriteLine($"  {name,-11} => {(info is null ? "<null>" : $"{info.Description} | mime={info.MimeType ?? "-"} | ext={info.Extensions ?? "-"}")}");
        if (name == "PNG" || name == "GZIP" || name == "ZIP")
        {
            foreach (var d in CompiledMagicEngine.DebugMatches)
            {
                Console.WriteLine($"      DBG {d}");
            }

            CompiledMagicEngine.DebugMatch = false;
        }

        if (info is not null)
        {
            ok++;
        }
    }

    Console.WriteLine($"smoke: {ok}/{samples.Length} samples matched (plain-text/empty may be null)");
    return 0;
}

static string? FindRepoRoot()
{
    var dir = new DirectoryInfo(AppContext.BaseDirectory);
    while (dir is not null)
    {
        if (File.Exists(Path.Combine(dir.FullName, "UotanStudio.slnx")))
        {
            return dir.FullName;
        }

        dir = dir.Parent;
    }

    return null;
}